def main() -> None:
    dest = Path(__file__).parent / "inputs" / "cost_assumptions.csv"
    dest.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for spec in SPECS:
        for i, case in enumerate(("low", "base", "high")):
            row = {
                "diagnostic": spec["diagnostic"],
                "method": spec["method"],
                "scale": spec["scale"],
                "case": case,
                "sample_type": spec["sample_type"],
                "price_year": spec["price_year"],
                "source": spec["source"],
                "confidence": spec["confidence"],
            }
            for field in NUMERIC:
                row[field] = spec[field][i]
            rows.append(row)
    with dest.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=HEADER)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {len(rows)} rows to {dest}")


if __name__ == "__main__":
    main()
